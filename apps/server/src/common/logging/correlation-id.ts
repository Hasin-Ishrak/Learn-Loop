import { randomUUID } from "node:crypto";
import type { IncomingMessage, ServerResponse } from "node:http";

type RequestWithId = IncomingMessage & { id?: string };

/** Read an existing correlation ID from the header or pino's request object. */
export function getCorrelationId(req: IncomingMessage): string | undefined {
  const header = req.headers["x-request-id"];
  const fromHeader = Array.isArray(header) ? header[0] : header;

  if (typeof fromHeader === "string" && fromHeader.length > 0) {
    return fromHeader;
  }

  const fromRequest = (req as RequestWithId).id;
  return typeof fromRequest === "string" && fromRequest.length > 0
    ? fromRequest
    : undefined;
}

/**
 * Reuse the incoming `x-request-id` (or one already generated by another
 * middleware), otherwise mint a UUID. Always mirrors it to the response header.
 */
export function resolveCorrelationId(
  req: IncomingMessage,
  res: ServerResponse,
): string {
  const correlationId = getCorrelationId(req) ?? randomUUID();

  (req as RequestWithId).id = correlationId;

  if (!res.headersSent && !res.getHeader("x-request-id")) {
    res.setHeader("x-request-id", correlationId);
  }

  return correlationId;
}
